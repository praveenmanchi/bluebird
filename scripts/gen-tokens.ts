export interface GenInputs {
  tokens: TokenSnapshot
  components: ComponentsSnapshot
  icons: IconsSnapshot
  /** figma/manifest.json → uiIconSets (which UI icon sets keep their own colours). */
  uiIconSets?: UiIconSet[]
  /** figma/logos/<name>.svg — brand logos (artwork, colours kept) and marks. */
  logos: Record<string, string>
  activeBrand: string
  /** Repo root, for the icon usage scan. */
  root?: string
}

export function readInputs(root = ROOT): GenInputs {
  const json = <T>(p: string) => JSON.parse(readFileSync(resolve(root, p), 'utf8')) as T
  const config = json<{ brand: { active: string } }>('plugin.config.json')
  const logoDir = resolve(root, LOGO_DIR)
  const logos: Record<string, string> = {}
  if (existsSync(logoDir)) for (const f of readdirSync(logoDir).filter((f) => f.endsWith('.svg')).sort()) logos[f.replace(/\.svg$/, '')] = readFileSync(resolve(logoDir, f), 'utf8')
  return {
    tokens: json<TokenSnapshot>('figma/tokens.json'),
    components: json<ComponentsSnapshot>('figma/components.json'),
    icons: json<IconsSnapshot>('figma/icons.json'),
    uiIconSets: json<{ uiIconSets?: UiIconSet[] }>('figma/manifest.json').uiIconSets ?? [],
    logos,
    activeBrand: config.brand.active,
    root,
  }
}

interface Declaration { name: string; value: string }

/**
 * Glyph names the plugin bundle can reach: string literals in src (components, shell,
 * features — not stories/tests/generated, and not src/dev, which is the browser-only
 * dev.html and reads the full table) and tab icons in plugin.config.json, plus every
 * name matching a template prefix like `disability-${kind}`. Storybook and tests still load
 * the full table through the @icons alias → generated.ts.
 */
export function usedIconNames(root: string, all: readonly string[]): string[] {
  const sources: string[] = []
  const skip = new Set([resolve(root, 'src/dev')])
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = resolve(dir, entry.name)
      if (entry.isDirectory()) { if (entry.name !== 'generated' && entry.name !== 'node_modules' && !skip.has(p)) walk(p); continue }
      if (!/\.(ts|tsx)$/.test(entry.name) || /\.(stories|test)\.tsx?$/.test(entry.name) || /generated(\.active)?\.ts$/.test(entry.name)) continue
      sources.push(readFileSync(p, 'utf8'))
    }
  }
  walk(resolve(root, 'src'))
  sources.push(readFileSync(resolve(root, 'plugin.config.json'), 'utf8'))
  const text = sources.join('\n')
  const literals = new Set([...text.matchAll(/['"`]([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g)].map((m) => m[1]!))
  const prefixes = [...text.matchAll(/`([a-z0-9-]+-)\$\{/g)].map((m) => m[1]!)
  return all.filter((name) => literals.has(name) || prefixes.some((prefix) => name.startsWith(prefix)))
}

function declarationsFor(input: GenInputs, collectionKey: string, mode: string): Declaration[] {
  const collection = input.tokens.collections.find((c) => c.key === collectionKey)
  if (!collection) throw new Error(`tokens.json has no "${collectionKey}" collection`)
  const out: Declaration[] = []
  for (const v of collection.variables) {
    const value = cssValueFor(v.name, v.type, v.values[mode] ?? null)
    if (value === null) continue
    out.push({ name: cssVarName(v.name), value })
  }
  return out
}

function block(selector: string, declarations: Declaration[]): string {
  return `${selector} {\n${declarations.map((d) => `  ${d.name}: ${d.value};`).join('\n')}\n}\n`
}

/** Fails on two variables (across collections) mapping to the same CSS name. */
export function assertNoCollisions(tokens: TokenSnapshot): void {
  const seen = new Map<string, string>()
  for (const c of tokens.collections) {
    for (const v of c.variables) {
      const key = cssVarName(v.name)
      const prev = seen.get(key)
      if (prev && prev !== c.name) throw new Error(`Token name collision: "${v.name}" in "${c.name}" and "${prev}" both become ${key}`)
      seen.set(key, c.name)
    }
  }
}

// Raw values the Figma components still carry without a variable. They are
// emitted as `--bb-derived-*` so code never hardcodes them, and they show up
// in the drift report as design-side gaps. A value shared by every variant is
// named after the layer; a value that differs per variant carries the variant.
const FONT_WEIGHTS: Record<string, number> = { thin: 100, extralight: 200, light: 300, regular: 400, medium: 500, semibold: 600, bold: 700, extrabold: 800, black: 900 }

/** Named styles ("ExtraBold") map through FONT_WEIGHTS; numeric ones ("300", as Museo Sans names
 *  its styles) are the weight itself when they fall in the CSS range 100–900. */
function weightFromStyle(style: string | undefined): number | undefined {
  if (!style) return undefined
  const key = style.toLowerCase().replace(/[\s-]/g, '').replace(/italic$/, '')
  if (/^\d+$/.test(key)) {
    const numeric = Number(key)
    return numeric >= 100 && numeric <= 900 ? numeric : undefined
  }
  return FONT_WEIGHTS[key]
}

function px(n: number): string { return `${Math.round(n * 1000) / 1000}px` }

type Raw = Record<string, unknown>

/** Property → css value pairs for one node's raw values. */
function rawDeclarationsFor(node: { p: string; t: string; b: Record<string, string>; r?: Raw }, options: { instanceSizes?: boolean } = {}): [string, string][] {
  const r = node.r ?? {}
  const out: [string, string][] = []
  const sizing = typeof r.layout === 'string' ? r.layout.split(' ') : []
  const [sizingH, sizingV] = [sizing[3], sizing[4]]
  if (typeof r.fill === 'string' && r.fill.startsWith('#')) out.push([node.t === 'TEXT' ? 'color' : 'fill', r.fill])
  if (typeof r.stroke === 'string' && r.stroke.startsWith('#')) out.push(['stroke', r.stroke])
  if (typeof r.opacity === 'number') out.push(['opacity', String(r.opacity)])
  if (node.t === 'TEXT') {
    if (typeof r.fontSize === 'number') out.push(['font-size', px(r.fontSize)])
    if (typeof r.font === 'string') {
      const family = r.font.replace(new RegExp(`\\s+${String(r.style ?? '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`), '').trim()
      out.push(['font-family', JSON.stringify(family)])
      const weight = weightFromStyle(typeof r.style === 'string' ? r.style : undefined)
      if (weight && !node.b.fontWeight) out.push(['font-weight', String(weight)])
    }
    if (typeof r.lineHeightPercent === 'number') out.push(['line-height', String(Math.round(r.lineHeightPercent * 10) / 1000)])
    if (typeof r.lineHeightPx === 'number') out.push(['line-height', px(r.lineHeightPx)])
    return out
  }
  if (typeof r.strokeWeight === 'number') out.push(['stroke-width', px(r.strokeWeight)])
  if (typeof r.radius === 'number') out.push(['radius', px(r.radius)])
  if (Array.isArray(r.radius)) out.push(['radius', (r.radius as number[]).map(px).join(' ')])
  for (const [k, css] of [['itemSpacing', 'gap'], ['paddingLeft', 'padding-left'], ['paddingRight', 'padding-right'], ['paddingTop', 'padding-top'], ['paddingBottom', 'padding-bottom']] as const) {
    if (typeof r[k] === 'number') out.push([css, px(r[k] as number)])
  }
  // Screens place instances at explicit sizes (a scaled logo); inside a component an instance's size belongs to its own set.
  if (Array.isArray(r.size) && (node.t !== 'INSTANCE' || options.instanceSizes)) {
    const [w, h] = r.size as [number, number]
    const container = node.t === 'FRAME' || node.t === 'COMPONENT'
    const fixedW = container ? sizingH === 'FIXED' || sizingH === undefined : true
    const fixedH = container ? sizingV === 'FIXED' || sizingV === undefined : true
    if (fixedW && !node.b.width) out.push(['width', px(w)])
    if (fixedH && !node.b.height) out.push(['height', px(h)])
  }
  return out
}

/** One layer's raw value for one css property, before it is named. */
interface DerivedEntry {
  variant: string
  /** Variant name as a token key (`brand-ikea`). */
  slug: string
  /** Figma node id, or the layer path for snapshots that predate ids. */
  nodeId: string
  /** Figma layer name (the last path segment), for reports. */
  layer: string
  /** Layer name as a token key, or `root` for the variant itself. */
  leaf: string
  /** 1-based position among this variant's layers that share `leaf` and carry raw values. */
  index: number
  /** Name segment the token is built from: `leaf`, or `leaf--index` once disambiguated. */
  part: string
  prop: string
  value: string
}

/** Layers in one variant whose shared name could hold only one of their values. */
export interface DerivedLayerCollision {
  set: string
  variant: string
  layer: string
  /** The same-named layers that carry raw values, in node order: `<layer>--<n>` is nodes[n - 1]. */
  nodes: string[]
  /** Occurrence-indexed tokens now holding the values the shared name dropped. */
  tokens: string[]
}

function derivedEntries(set: ComponentSetSnapshot): DerivedEntry[] {
  const entries: DerivedEntry[] = []
  for (const variant of set.variants) {
    const slug = tokenKeyFromVariableName(variant.name.replace(/[=,]/g, '-'))
    const instancePaths = new Set(variant.nodes.filter((n) => n.t === 'INSTANCE').map((n) => n.p))
    const seen = new Map<string, number>()
    for (const node of variant.nodes) {
      const isRoot = !node.p.includes('/')
      // Layers inside an instance belong to their own set — unless this set overrides them (`o`), in which case the overridden values are this set's design.
      if (!node.o && [...instancePaths].some((ip) => node.p.startsWith(`${ip}/`))) continue
      const declarations = rawDeclarationsFor(node, { instanceSizes: Boolean(set.dir) })
      if (!declarations.length) continue
      const layer = isRoot ? variant.name : node.p.split('/').pop() ?? ''
      const leaf = isRoot ? 'root' : tokenKeyFromVariableName(layer)
      const index = (seen.get(leaf) ?? 0) + 1
      seen.set(leaf, index)
      for (const [prop, value] of declarations) {
        entries.push({ variant: variant.name, slug, nodeId: node.id ?? node.p, layer, leaf, index, part: leaf, prop, value })
      }
    }
  }
  return entries
}

/** `<set>-<part>-<prop>` when every entry of a part/prop agrees, `<set>-<part>-<variant>-<prop>` otherwise; [name, entry] in emission order. */
function nameEntries(code: string, entries: readonly DerivedEntry[]): [string, DerivedEntry][] {
  const table = new Map<string, Map<string, DerivedEntry[]>>() // (part|prop) → value → entries
  for (const e of entries) {
    const key = `${e.part}|${e.prop}`
    const byValue = table.get(key) ?? new Map<string, DerivedEntry[]>()
    byValue.set(e.value, [...(byValue.get(e.value) ?? []), e])
    table.set(key, byValue)
  }
  return [...table.values()].flatMap((byValue) => [...byValue.values()].flat().map((e): [string, DerivedEntry] => {
    // Disabled opacity keeps its historical name (state-scoped) so component CSS stays stable.
    const disabledOpacity = e.prop === 'opacity' && e.part === 'root'
    if (byValue.size === 1) return [disabledOpacity ? `${code}-disabled-opacity` : `${code}-${e.part}-${e.prop}`, e]
    return [disabledOpacity ? `${code}-${e.slug}-opacity` : `${code}-${e.part}-${e.slug}-${e.prop}`, e]
  }))
}

function collisionsOf(setCode: string, entries: readonly DerivedEntry[], rescued: readonly [string, DerivedEntry][]): DerivedLayerCollision[] {
  const groupOf = (e: DerivedEntry) => `${e.variant}\u0000${e.leaf}`
  const hit = new Set(rescued.map(([, e]) => groupOf(e)))
  return [...new Set(entries.map(groupOf))].filter((g) => hit.has(g)).map((g) => {
    const members = entries.filter((e) => groupOf(e) === g)
    return {
      set: setCode,
      variant: members[0]!.variant,
      layer: members[0]!.layer,
      nodes: [...new Set(members.map((e) => e.nodeId))],
      tokens: [...new Set(rescued.filter(([, e]) => groupOf(e) === g).map(([name]) => `--bb-derived-${name}`))].sort(),
    }
  })
}

function buildDerived(components: ComponentsSnapshot): { declarations: Declaration[]; collisions: DerivedLayerCollision[] } {
  const out = new Map<string, string>()
  const collisions: DerivedLayerCollision[] = []
  for (const set of components.sets) {
    if (set.status === 'planned' || set.status === 'alias') continue // no code reads them; keeps the plugin CSS small
    const code = tokenKeyFromVariableName(set.code.replace(/([a-z])([A-Z])/g, '$1-$2'))
    const entries = derivedEntries(set)
    const named = nameEntries(code, entries)
    const kept = new Map(named.map(([name, e]) => [name, e.value])) // later writes win, as they always have
    // Same-named layers in one variant land on one name and only the last value survives. Component CSS
    // already reads those names, so they stay as they are; each value that lost gets its layer's
    // occurrence index instead (`vector--1`). tokenKeyFromVariableName collapses `-+`, so a real layer
    // name does not produce `--`; the guard below still refuses to shadow an existing token.
    const lost = named.filter(([name, e]) => kept.get(name) !== e.value).map(([, e]) => ({ ...e, part: `${e.leaf}--${e.index}` }))
    const rescued = nameEntries(code, lost)
    for (const [name] of rescued) if (kept.has(name)) throw new Error(`derived token ${name} would overwrite an existing one`)
    for (const [name, value] of [...kept, ...rescued.map(([n, e]): [string, string] => [n, e.value])]) out.set(`--bb-derived-${name}`, value)
    collisions.push(...collisionsOf(set.code, entries, rescued))
  }
  return {
    declarations: [...out.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, value]) => ({ name, value })),
    collisions,
  }
}

export function derivedDeclarations(components: ComponentsSnapshot): Declaration[] {
  return buildDerived(components).declarations
}

/** Same-named Figma layers whose values needed occurrence-indexed tokens — the designer should rename them. */
export function derivedLayerCollisions(components: ComponentsSnapshot): DerivedLayerCollision[] {
  return buildDerived(components).collisions
}

function boundTokensOf(set: ComponentSetSnapshot): string[] {
  const names = new Set<string>()
  for (const variant of set.variants) for (const node of variant.nodes) for (const v of Object.values(node.b)) if (!v.startsWith('lib:')) names.add(v)
  return [...names].sort()
}

function tsArray(items: readonly string[], indent = '  '): string {
  return items.map((i) => `${indent}${JSON.stringify(i)},`).join('\n')
}

/** Figma exports path data with 4–6 decimals; 2 are indistinguishable at icon sizes and halve the bundle. */
export function roundPathData(svg: string, decimals = 2): string {
  const scale = 10 ** decimals
  return svg.replace(/ d="([^"]*)"/g, (_, d: string) => ` d="${d.replace(/-?\d*\.\d+/g, (n) => String(Math.round(Number(n) * scale) / scale))}"`)
}

/** UI icons sit on a 24-unit grid and render at 12–24px, so one decimal (≤0.03px off at 16px) is enough. */
const UI_ICON_DECIMALS = 1

/** Lossless path-data minification (as svgo does): `0.5` → `.5`, `1 -2` → `1-2`. */
export function minifyPathData(svg: string): string {
  return svg.replace(/ d="([^"]*)"/g, (_, d: string) => ` d="${d.replace(/(^|[^\d.])0\./g, '$1.').replace(/ -/g, '-')}"`)
}

/** Strip size attributes, drop the wrapper, and route colours through currentColor. */
export function normalizeSvg(svg: string): { viewBox: string; body: string } {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 24 24'
  const body = roundPathData(svg)
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/(fill|stroke)="(#[0-9a-fA-F]{3,8}|white|black)"/g, '$1="currentColor"')
    .trim()
  return { viewBox, body }
}

/** The tokens UI icon sets are bound to (figma/manifest.json → uiIconSets), and how each reaches the SVG. */
const UI_ICON_TONES: Record<string, 'currentColor' | 'var'> = {
  'icon/glyph/default': 'currentColor',
  'icon/glyph/muted': 'var',
  'surface/canvas': 'var',
  'surface/accent': 'var',
}

/**
 * REST renders bound paints at the Brand UI default mode, so a UI icon colour is matched back to
 * its token by that mode's hex. Glyph colour stays currentColor (the Icon `tone` still works);
 * the secondary tones become `style` fills because SVG presentation attributes ignore var().
 */
export function uiIconTones(tokens: TokenSnapshot): Record<string, string> {
  const brand = tokens.collections.find((c) => c.key === 'brand')
  if (!brand) throw new Error('tokens.json has no "brand" collection')
  const mode = brand.defaultMode
  const tones: Record<string, string> = {}
  for (const [name, kind] of Object.entries(UI_ICON_TONES)) {
    const value = brand.variables.find((v) => v.name === name)?.values[mode]
    if (typeof value !== 'string') throw new Error(`Brand UI has no colour for ${name} in ${mode}`)
    const hex = value.toLowerCase()
    if (tones[hex]) throw new Error(`${name} and another UI icon tone share ${hex} in ${mode}; the export cannot tell them apart`)
    tones[hex] = kind === 'currentColor' ? 'currentColor' : `var(${cssVarName(name)})`
  }
  return tones
}

const HEX_NAMES: Record<string, string> = { white: '#ffffff', black: '#000000' }

/** A UI icon body: colours that match a tone become tokens, anything else (red badges, app marks) stays as drawn. */
export function normalizeUiSvg(svg: string, tones: Readonly<Record<string, string>>, rawColors = false): { viewBox: string; body: string } {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 24 24'
  const body = minifyPathData(roundPathData(svg, UI_ICON_DECIMALS))
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim()
  if (rawColors) return { viewBox, body }
  return {
    viewBox,
    body: body.replace(/(fill|stroke)="(#[0-9a-fA-F]{6}|white|black)"/g, (match, prop: string, colour: string) => {
      const tone = tones[(HEX_NAMES[colour] ?? colour).toLowerCase()]
      if (!tone) return match
      return tone === 'currentColor' ? `${prop}="currentColor"` : `style="${prop}:${tone}"`
    }),
  }
}

export function generate(input: GenInputs): Record<string, string> {
  assertNoCollisions(input.tokens)
  const brand = input.tokens.collections.find((c) => c.key === 'brand')
  if (!brand) throw new Error('tokens.json has no brand collection')
  const brandIds = brand.modes.map(brandIdFromMode)
  if (!brandIds.includes(input.activeBrand)) {
    throw new Error(`plugin.config.json brand.active "${input.activeBrand}" is not a Brand mode (${brandIds.join(', ')})`)
  }

  const files: Record<string, string> = {}
  const primitives = input.tokens.collections.find((c) => c.key === 'primitives')
  const semantics = input.tokens.collections.find((c) => c.key === 'semantics')
  if (!primitives || !semantics) throw new Error('tokens.json needs primitives and semantics collections')
  // Semantics carries the brand switch when it has one mode per Brand mode; a single-mode
  // Semantics is brand-agnostic and lands on :root next to the primitives.
  const semanticsPerBrand = semantics.modes.length > 1
  const semanticsModeFor = (brandMode: string) => (semantics.modes.includes(brandMode) ? brandMode : semantics.defaultMode)
  const base = [
    ...declarationsFor(input, 'primitives', primitives.defaultMode),
    ...(semanticsPerBrand ? [] : declarationsFor(input, 'semantics', semantics.defaultMode)),
  ]
  files[`${GEN_DIR}/base.css`] = HEADER + block(':root', base)

  const derived = derivedDeclarations(input.components)
  files[`${GEN_DIR}/derived.css`] = HEADER +
    '/* Raw values still hardcoded in the Figma components (no variable bound). Promote them to variables in Figma and they move to brand.*.css automatically. */\n' +
    block(':root', derived)

  for (const mode of brand.modes) {
    const id = brandIdFromMode(mode)
    const perBrand = [
      ...(semanticsPerBrand ? declarationsFor(input, 'semantics', semanticsModeFor(mode)) : []),
      ...declarationsFor(input, 'brand', mode),
    ]
    files[`${GEN_DIR}/brand.${id}.css`] = HEADER + block(`[data-brand="${id}"]`, perBrand)
  }
  files[`${GEN_DIR}/all.css`] = HEADER + `@import "./base.css";\n@import "./derived.css";\n${brandIds.map((id) => `@import "./brand.${id}.css";`).join('\n')}\n`
  files[`${GEN_DIR}/active.css`] = HEADER + `@import "./base.css";\n@import "./derived.css";\n@import "./brand.${input.activeBrand}.css";\n`

  const tokenNames = [...new Set([
    ...base.map((d) => d.name),
    ...declarationsFor(input, 'semantics', semantics.defaultMode).map((d) => d.name),
    ...derived.map((d) => d.name),
    ...declarationsFor(input, 'brand', brand.modes[0]!).map((d) => d.name),
  ])].sort()
  const builtSets = input.components.sets.filter((set) => !set.status || set.status === 'built')
  const componentTokens = builtSets.map((set) => `  ${set.code}: [\n${tsArray(boundTokensOf(set).map(cssVarName), '    ')}\n  ],`).join('\n')
  const figmaComponents = builtSets.map((set) =>
    `  ${set.code}: { id: ${JSON.stringify(set.id)}, name: ${JSON.stringify(set.name)}, variants: [\n` +
    set.variants.map((v) => `    { id: ${JSON.stringify(v.id)}, name: ${JSON.stringify(v.name)}, props: ${JSON.stringify(v.props)} },`).join('\n') +
    `\n  ] },`).join('\n')

  files[`${GEN_DIR}/tokens.ts`] = TS_HEADER +
    `export const FIGMA_FILE_KEY = ${JSON.stringify(input.tokens.fileKey)}\n` +
    `export const BRANDS = [\n${tsArray(brandIds)}\n] as const\n` +
    `export type BrandId = (typeof BRANDS)[number]\n` +
    `export const BRAND_LABELS: Record<BrandId, string> = {\n${brand.modes.map((m) => `  ${brandIdFromMode(m)}: ${JSON.stringify(m)},`).join('\n')}\n}\n` +
    `export const BRAND_MODES: Record<BrandId, string> = BRAND_LABELS\n` +
    `export const TOKEN_NAMES = [\n${tsArray(tokenNames)}\n] as const\n` +
    `export type TokenName = (typeof TOKEN_NAMES)[number]\n` +
    `/** CSS custom properties each code component must consume (bound in the Figma component set). */\n` +
    `export const COMPONENT_TOKENS = {\n${componentTokens}\n} as const\n` +
    `export type ComponentCode = keyof typeof COMPONENT_TOKENS\n` +
    `export const FIGMA_COMPONENTS = {\n${figmaComponents}\n} as const\n` +
    `/** Figma sets mapped in figma/components.json but not built yet (docs/figma-token-mapping.md). */\n` +
    `export const PLANNED_COMPONENTS = {\n${input.components.sets.filter((set) => set.status === 'planned').map((set) => `  ${set.code}: { id: ${JSON.stringify(set.id)}, name: ${JSON.stringify(set.name)}, variants: ${set.variants.length} },`).join('\n')}\n} as const\n` +
    `/** Figma sets covered by another code component (duplicates, or glyph sources folded into Icon / BrandLogo). */\n` +
    `export const ALIAS_COMPONENTS = {\n${input.components.sets.filter((set) => set.status === 'alias').map((set) => `  ${set.code}: { id: ${JSON.stringify(set.id)}, name: ${JSON.stringify(set.name)}, aliasOf: ${JSON.stringify(set.aliasOf ?? '')} },`).join('\n')}\n} as const\n`

  const uiTones = Object.values(input.icons.icons).some((icon) => icon.set) ? uiIconTones(input.tokens) : {}
  const rawSets = new Set((input.uiIconSets ?? []).filter((set) => set.rawColors).map((set) => set.prefix))
  const iconEntries = Object.entries(input.icons.icons).sort(([a], [b]) => a.localeCompare(b)).map(([key, icon]) => {
    const { viewBox, body } = icon.set ? normalizeUiSvg(icon.svg, uiTones, rawSets.has(icon.set)) : normalizeSvg(icon.svg)
    return `  ${JSON.stringify(key)}: { id: ${JSON.stringify(icon.id)}, viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} },`
  })
  const markEntries = Object.entries(input.icons.marks).map(([key, mark]) => {
    const { viewBox, body } = normalizeSvg(mark.svg)
    return `  ${JSON.stringify(key)}: { id: ${JSON.stringify(mark.id)}, viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} },`
  })
  const logoEntries = Object.entries(input.logos).map(([key, svg]) => {
    const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 24 24'
    const body = roundPathData(svg).replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim()
    // Marks are single-colour glyphs bound to a token; logos are multi-colour artwork and keep their fills.
    const isMark = MONO_LOGOS.has(key)
    const finalBody = isMark ? body.replace(/(fill|stroke)="(#[0-9a-fA-F]{3,8}|white|black)"/g, '$1="currentColor"') : body
    return `  ${JSON.stringify(key)}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(finalBody)} },`
  })
  const logoHeader = TS_HEADER +
    `// Brand logos are artwork exported from the Figma "brand logos" set (figma/logos/*.svg); colours are intentionally not tokenised.\n` +
    `export interface Artwork { viewBox: string; body: string }\n`
  files[LOGO_GEN] = logoHeader +
    `export const LOGOS = {\n${logoEntries.join('\n')}\n} as const satisfies Record<string, Artwork>\n` +
    `export type LogoName = keyof typeof LOGOS\n`
  // The plugin bundle inlines everything, so it only ships the active brand's logo plus the
  // brand-independent artwork (HCL mark, Fabric wordmark, integration logos).
  const activeEntries = logoEntries.filter((line) => line.startsWith(`  ${JSON.stringify(input.activeBrand)}:`) || !brandIds.some((id) => line.startsWith(`  ${JSON.stringify(id)}:`)))
  files[LOGO_GEN.replace(/generated\.ts$/, 'generated.active.ts')] = logoHeader +
    `// Active brand only (plugin.config.json → brand.active = ${input.activeBrand}). Storybook and tests alias @logos to ./generated.ts instead.\n` +
    `import type { LogoName } from './generated'\n` +
    `export type { LogoName }\n` +
    `export const LOGOS: Partial<Record<LogoName, Artwork>> = {\n${activeEntries.join('\n')}\n}\n`

  files[ICON_GEN] = TS_HEADER +
    `export interface Glyph { id: string; viewBox: string; body: string }\n` +
    `export const ICONS = {\n${iconEntries.join('\n')}\n} as const satisfies Record<string, Glyph>\n` +
    `export type IconName = keyof typeof ICONS\n` +
    `export const MARKS = {\n${markEntries.join('\n')}\n} as const satisfies Record<string, Glyph>\n` +
    `export type MarkName = keyof typeof MARKS\n`
  // The plugin bundle inlines everything, so it ships only the glyphs the code can reference.
  const used = new Set(usedIconNames(input.root ?? ROOT, Object.keys(input.icons.icons)))
  const activeIconEntries = iconEntries.filter((line) => used.has(/^ {2}"([^"]+)"/.exec(line)?.[1] ?? ''))
  files[ICON_ACTIVE_GEN] = TS_HEADER +
    `// Glyphs referenced from src/ and plugin.config.json only (${activeIconEntries.length} of ${iconEntries.length}). Storybook and tests alias @icons to ./generated.ts instead.\n` +
    `import type { Glyph, IconName, MarkName } from './generated'\n` +
    `export type { Glyph, IconName, MarkName }\n` +
    `export const ICONS: Partial<Record<IconName, Glyph>> = {\n${activeIconEntries.join('\n')}\n}\n` +
    `export const MARKS: Record<MarkName, Glyph> = {\n${markEntries.join('\n')}\n}\n`

  return files
}

export function writeFiles(files: Record<string, string>, root = ROOT): string[] {
  const changed: string[] = []
  for (const [rel, content] of Object.entries(files)) {
    const abs = resolve(root, rel)
    mkdirSync(dirname(abs), { recursive: true })
    if (existsSync(abs) && readFileSync(abs, 'utf8') === content) continue
    writeFileSync(abs, content)
    changed.push(rel)
  }
  return changed
}

