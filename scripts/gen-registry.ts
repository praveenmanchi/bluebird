// Generates the feature registries from plugin.config.json.
//
// Only tabs that are enabled AND referenced by at least one persona are
// imported. Disabled tabs are therefore not just hidden — they are absent from
// the bundle entirely (UI and sandbox).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { loadConfig } from '../src/shared/config/load'

const root = resolve(import.meta.dirname, '..')
const raw = JSON.parse(readFileSync(resolve(root, 'plugin.config.json'), 'utf8'))
const config = loadConfig(raw)

const bundled = Object.keys(config.tabs).filter((id) => {
  const tab = config.tabs[id]
  const referenced = Object.values(config.personas).some((p) => p.tabs.includes(id))
  return tab?.enabled && referenced
})

for (const id of bundled) {
  const dir = resolve(root, 'src/features', id)
  if (!existsSync(dir)) throw new Error(`Tab "${id}" is enabled in plugin.config.json but src/features/${id} does not exist.`)
}

const header = '// AUTO-GENERATED by scripts/gen-registry.ts — do not edit. Re-run `npm run gen`.\n'

const uiFile = header +
  bundled.map((id) => `import * as f_${safe(id)} from '@features/${id}/manifest'\nimport { Tab as Tab_${safe(id)} } from '@features/${id}/ui/Tab'`).join('\n') +
  `\nimport type { FeatureEntry } from '@shared/feature'\n\n` +
  `export const features: readonly FeatureEntry[] = [\n` +
  bundled.map((id) => `  { manifest: f_${safe(id)}.manifest, Tab: Tab_${safe(id)} },`).join('\n') +
  `\n]\n`

const sandboxFile = header +
  bundled.map((id) => `import { handlers as h_${safe(id)} } from '@features/${id}/sandbox/handler'`).join('\n') +
  `\nimport type { HandlerMap } from '@shared/bridge/sandbox-router'\n\n` +
  `export const handlers: HandlerMap = {\n` +
  bundled.map((id) => `  ...h_${safe(id)},`).join('\n') +
  `\n}\n`

write(resolve(root, 'src/shell/registry.generated.ts'), uiFile)
write(resolve(root, 'src/sandbox/registry.generated.ts'), sandboxFile)
console.log(`[gen] bundled tabs: ${bundled.length ? bundled.join(', ') : '(none)'}`)

function safe(id: string): string { return id.replace(/[^a-zA-Z0-9_]/g, '_') }
function write(file: string, content: string): void {
  mkdirSync(dirname(file), { recursive: true })
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return
  writeFileSync(file, content)
}
